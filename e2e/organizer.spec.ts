import { test, expect, Page } from '@playwright/test';
async function wedding(page: Page, name = 'Nosso casamento') {
  await page.goto('/casamentos/novo');
  await page.getByLabel('Nome do casamento', { exact: true }).fill(name);
  await page.getByLabel('Nome completo da noiva').fill('Ana');
  await page.getByLabel('Nome completo do noivo').fill('João');
  await page.getByRole('button', { name: 'Salvar casamento', exact: true }).click();
  await expect(page).toHaveURL(/dashboard$/);
}
test('lembretes e notas persistem, concluem e ficam separados por casamento', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await wedding(page);
  await page.goto('/lembretes');
  await page.getByRole('button', { name: 'Novo lembrete', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Título').fill('Buscar alianças');
  await dialog.getByLabel('Detalhes').fill('Levar o comprovante da joalheria.');
  await dialog.getByLabel('Data do lembrete', { exact: true }).fill('01/01/2020');
  await dialog.getByLabel('Destacar como importante').check();
  await dialog.getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('.organizer-item')).toContainText('Atrasado');
  await page.getByRole('button', { name: 'Nova anotação', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Título').fill('Ideias de decoração');
  await dialog.getByLabel('Detalhes').fill('Flores brancas\nVelas na recepção');
  await expect(dialog.getByLabel('Data do lembrete')).toHaveCount(0);
  await dialog.getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.reload();
  await expect(page.locator('.organizer-item')).toHaveCount(2);
  await page.getByRole('button', { name: 'Concluir', exact: true }).click();
  await expect(page.locator('.organizer-item')).toHaveCount(1);
  await page.getByLabel('Mostrar', { exact: true }).selectOption('completed');
  await expect(page.locator('.organizer-item')).toContainText('Buscar alianças');
  await page.getByRole('button', { name: 'Reabrir', exact: true }).click();
  await page.getByLabel('Mostrar', { exact: true }).selectOption('all');
  await page.getByRole('button', { name: 'Editar Ideias de decoração', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Título').fill('Decoração escolhida');
  await page.getByRole('dialog').getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.screenshot({ path: 'artifacts/lembretes-celular.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto('/dashboard');
  await expect(page.locator('.dashboard-reminders')).toContainText('Buscar alianças');
  await page.getByRole('link', { name: 'Dados do casamento', exact: true }).click();
  await page.getByRole('button', { name: 'Salvar casamento', exact: true }).click();
  await expect(page).toHaveURL(/dashboard$/);
  await page.goto('/lembretes');
  await expect(page.locator('.organizer-item')).toHaveCount(2);
  await page.getByRole('button', { name: 'Excluir Decoração escolhida', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.organizer-item')).toHaveCount(1);
  await wedding(page, 'Outro casamento');
  await page.goto('/lembretes');
  await expect(page.locator('.organizer-item')).toHaveCount(0);
});
test('aviso de conta desaparece ao pagar e modal cabe no celular deitado', async ({ page }) => {
  await wedding(page);
  await page.goto('/financeiro/despesas/nova');
  await page.getByLabel('Descrição *', { exact: true }).fill('Flores da cerimônia');
  await page.locator('#supplier').fill('Floricultura');
  await page.getByLabel('Valor total combinado *', { exact: true }).fill('500');
  await page.getByLabel('Vencimento / data da entrada *', { exact: true }).fill('01/01/2020');
  await page.getByRole('button', { name: 'Salvar gasto', exact: true }).click();
  await expect(
    page.getByRole('heading', { name: 'Detalhes da despesa', exact: true }),
  ).toBeVisible();
  const expense = page.url();
  await page.goto('/lembretes');
  await expect(page.locator('.organizer-bills')).toContainText('Flores da cerimônia');
  await page.goto(expense);
  await page.getByRole('button', { name: 'Registrar pagamento', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Registrar', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.goto('/lembretes');
  await expect(page.locator('.organizer-bills')).toHaveCount(0);
  await page.setViewportSize({ width: 667, height: 390 });
  await page.getByRole('button', { name: 'Novo lembrete', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('button', { name: 'Salvar', exact: true })).toBeInViewport();
  await dialog.getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(dialog.getByRole('alert')).toBeVisible();
  const bounds = await dialog.boundingBox();
  expect(bounds!.height).toBeLessThanOrEqual(390);
});

// Traduz identificadores SQL sem modificar literais/JSON, comentários ou parâmetros RPC.
export function traduzirSQL(sql) {
  return sql.replace(
    /'(?:''|[^'])*'|--[^\n]*|\/\*[\s\S]*?\*\/|\b[a-z_][a-z_0-9]*\b/gi,
    (token) => colunas[token] ?? tabelas[token] ?? token,
  );
}
